def tile_cm(d):
    """Medida real de la imagen entera (ancho, alto) en cm."""
    if "tile_cm" in d:
        return tuple(d["tile_cm"])
    return (d["piezas"][0] * (d["pieza_cm"][0] + d["junta_cm"]),
            d["piezas"][1] * (d["pieza_cm"][1] + d["junta_cm"]))


